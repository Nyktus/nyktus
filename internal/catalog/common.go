// Category groups deceptions by what they pretend to be.
type Category string

// Categories of deceptions.
const (
	// CategoryIdentity pretends to be credentials or accounts.
	CategoryIdentity Category = "identity"
	// CategoryNetwork pretends to be access to hosts or networks, such as VPN
	// or SSH configurations.
	CategoryNetwork Category = "network"
	// CategoryData pretends to be documents, exports or backups.
	CategoryData Category = "data"
	// CategoryEndpoint pretends to be files of a workstation, such as
	// shortcuts or scripts.
	CategoryEndpoint Category = "endpoint"
	// CategoryApplication pretends to be configuration or credentials of an
	// application.
	CategoryApplication Category = "application"
	// CategoryCloud pretends to be resources of a cloud account, such as
	// users, secrets or storage.
	CategoryCloud Category = "cloud"
)

// Categories lists every category.
var Categories = []Category{CategoryIdentity, CategoryNetwork, CategoryData, CategoryEndpoint, CategoryApplication, CategoryCloud}

// Languages lists the languages of the texts and guides of every entry.
var Languages = []string{"en", "de"}

// Text is a text in every language of Languages.
type Text map[string]string

// Limits of the entries of the catalog.
const (
	maxTitleLength   = 100
	maxSummaryLength = 500
	maxLabelLength   = 60
	maxHoneytokens   = 10
	maxHoneypots     = 10
	maxFiles         = 20
	// MaxFileBytes bounds every file and every guide of an entry.
	MaxFileBytes = 256 << 10
)

var (
	entryID = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)
	// guideFile is the name of a guide next to the definition.
	guideFile = regexp.MustCompile(`^[a-z0-9]+([._-][a-z0-9]+)*\.md$`)
	// fileName is a name that every operating system accepts: no separators,
	// no leading dot or hyphen, no trailing dot or space.
	fileName = regexp.MustCompile(`^[A-Za-z0-9]([A-Za-z0-9 ._-]{0,98}[A-Za-z0-9_-])?$`)
	// reservedName is a name that Windows keeps for a device, with or without an
	// extension.
	reservedName = regexp.MustCompile(`(?i)^(con|prn|aux|nul|com[1-9]|lpt[1-9])(\..*)?$`)
)

// maxIDLength is the length of an identifier of a deception.
const maxIDLength = 64

// markers must not appear in a file, in any case: they name the product or
// what a file is, or credit the catalog, and whoever finds them knows that the
// file is a trap. Guides are read by administrators and may use them.
var markers = []string{
	"nyktus", "honeytoken", "honeypot", "canary", "decoy", "deception", "creative commons", "generated by",
	"<no value>",
}

// placeholder finds the words that stand in a file where the administrator
// enters the host name or the URL of a honeytoken. They are visible on
// purpose: a file that still holds one is not placed yet, and the word is no
// host that resolves. Where a deception has several honeytokens of a kind, the
// word names the slot as well, such as Honeytoken-Domain-Database.
var placeholder = regexp.MustCompile(`Honeytoken-(Domain|URL)(-[A-Z][A-Za-z0-9]{0,31})?`)

// licenseNotice finds the short form of a Creative Commons license, such as
// "CC BY 4.0" or "cc-by-sa", as a word of its own, so that words such as
// "gcc by default" do not match.
var licenseNotice = regexp.MustCompile(`(?i)\bcc[ -]by\b`)

// findMarker returns the first marker that the text of a file contains, in any
// case, or "". The placeholders do not count. The identifiers ids are markers
// as well: they are the same in every installation.
func findMarker(text string, ids ...string) string {
	text = placeholder.ReplaceAllString(text, "")
	if m := licenseNotice.FindString(text); m != "" {
		return strings.ToLower(m)
	}
	lower := strings.ToLower(text)
	for _, m := range markers {
		if strings.Contains(lower, m) {
			return m
		}
	}
	for _, id := range ids {
		if strings.Contains(lower, id) {
			return id
		}
	}
	return ""
}

// decodeStrict decodes JSON into v, rejecting unknown fields and anything
// after the value.
func decodeStrict(b []byte, v any) error {
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		return err
	}
	if _, err := dec.Token(); !errors.Is(err, io.EOF) {
		return errors.New("unexpected data after the definition")
	}
	return nil
}

// validActivities accepts at least one distinct Engage activity of the
// bundled version.
func validActivities(ids []string) error {
	if len(ids) == 0 || len(ids) > 20 {
		return errors.New("engage_activities: want 1 to 20 activities")
	}
	for i, id := range ids {
		if _, ok := engage.Lookup(id); !ok || slices.Contains(ids[:i], id) {
			return fmt.Errorf("engage_activities: %q is unknown or listed twice", id)
		}
	}
	return nil
}

// validText accepts a text in every language of Languages, each of 1 to max
// printable characters on one line without surrounding spaces.
func validText(t Text, maxRunes int) error {
	if len(t) != len(Languages) {
		return fmt.Errorf("want a text in each of %v", Languages)
	}
	for _, lang := range Languages {
		s := t[lang]
		n := utf8.RuneCountInString(s)
		if n < 1 || n > maxRunes || strings.TrimSpace(s) != s || !utf8.ValidString(s) {
			return fmt.Errorf("%s: want 1 to %d characters without surrounding spaces", lang, maxRunes)
		}
		for _, r := range s {
			if !unicode.IsGraphic(r) {
				return fmt.Errorf("%s: contains the character %U", lang, r)
			}
		}
	}
	return nil
}

// validContent accepts the text of a file or a guide: valid UTF-8 without a NUL
// or another control character, apart from line breaks and tabs, and without
// a byte order mark, which a shell or a parser would take for content.
func validContent(b []byte) error {
	if len(b) == 0 || len(b) > MaxFileBytes {
		return fmt.Errorf("want 1 to %d bytes", MaxFileBytes)
	}
	if !utf8.Valid(b) {
		return errors.New("not valid UTF-8")
	}
	if bytes.HasPrefix(b, []byte("\xef\xbb\xbf")) {
		return errors.New("starts with a byte order mark")
	}
	for _, r := range string(b) {
		if unicode.IsControl(r) && r != '\n' && r != '\r' && r != '\t' {
			return fmt.Errorf("contains the character %U", r)
		}
	}
	return nil
}
